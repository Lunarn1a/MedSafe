"""Freeze auditable, weakly labeled source examples for the topic selector.

Labels describe topics mentioned in source management text. They are generated by
documented annotation rules, not clinician review. No model predictions are labels.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from source_topics import TOPICS, ADVICE, model_input, training_labels
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.neighbors import NearestNeighbors


def main():
    source = json.loads((ROOT / "backend/data/source_details.json").read_text(encoding="utf-8"))["records"]
    examples = []
    for key, record in sorted(source.items()):
        text = model_input(record)
        has_management = record["management"] not in ("", "-") or ADVICE.search(record["interaction"])
        if len(text.split()) < 8 or not has_management:
            continue
        evidence = training_labels(record)
        examples.append({"pair_id": key, "input_text": text,
                         "labels": {topic: int(topic in evidence) for topic in TOPICS},
                         "label_evidence": evidence, "source_url": record["source_url"],
                         "source_sha256": record["source_sha256"],
                         "annotation_method": "Rule-assisted management-topic annotation; not independent clinical labels."})
    # Cluster near-duplicate mechanisms before splitting; normalise names/numbers
    # to keep simple drug-name substitutions in the same source family.
    names = json.loads((ROOT / "drugs.json").read_text(encoding="utf-8-sig"))["drugs"]
    name_pattern = re.compile("|".join(re.escape(n) for n in sorted(names, key=len, reverse=True)), re.I)
    texts = []
    for row in examples:
        text = re.sub(r"^severity_\w+\s+", "", row["input_text"])
        text = name_pattern.sub("medicine", text)
        texts.append(re.sub(r"\d+", "number", text.casefold()))
    vectors = TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), max_features=12000).fit_transform(texts)
    neighbors = NearestNeighbors(metric="cosine", radius=0.12).fit(vectors).radius_neighbors(vectors, return_distance=False)
    parents = list(range(len(examples)))
    def find(i):
        while parents[i] != i:
            parents[i] = parents[parents[i]]
            i = parents[i]
        return i
    for i, matches in enumerate(neighbors):
        for j in matches:
            a, b = find(i), find(int(j))
            parents[max(a, b)] = min(a, b)
    for i, row in enumerate(examples):
        row["group_id"] = "source_family_" + hashlib.sha256(texts[find(i)].encode()).hexdigest()[:16]
    payload = {"schema_version": 1, "task": "Predict source management topics from mechanism text",
               "label_method": "Weak supervision from source text; no clinician-verified targets.",
               "grouping": "Character TF-IDF similarity >=0.88 after normalising drug names and numbers; connected components stay together.",
               "topics": list(TOPICS), "examples": examples}
    target = ROOT / "training/source_topic_examples.json"
    target.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"source_records": len(source), "labeled_examples": len(examples), "groups": len({r['group_id'] for r in examples})}, indent=2))


if __name__ == "__main__":
    main()
